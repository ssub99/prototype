/* ------------------------------------------------------------------ */
/* Registry: every Components-page master → code call                 */
/* ------------------------------------------------------------------ */

const familyOf = (name) => name.split("/")[0].trim();
const registry = {
  source: {
    file: "(Local)Rallyz Design Library_231028",
    page: "Components",
    builtAt: new Date().toISOString().slice(0, 10),
    note: "Figma keeps one master per state. Code exposes one component per family with props. 'code' is the JS call that renders that master.",
  },
  paintStyles: paintByName,
  textStyles: styles.textStyles.map((t) => ({ name: t.name, className: "rz-t-" + t.name.toLowerCase().replace("/", "-") })),
  icons: Object.keys(icons).length,
  components: components.components
    .filter((c) => c.page === "Components")
    .map((c) => ({ id: c.id, key: c.key, name: c.name, family: familyOf(c.name), spec: `figma/spec/${c.id.replace(":", "_")}.json`, png: `figma/png/${c.id.replace(":", "_")}.png` })),
  componentSets: components.componentSets.map((s) => ({ id: s.id, name: s.name, variants: s.variants.map((v) => ({ id: v.id, name: v.name })) })),
};
writeFileSync(join(root, "registry.json"), JSON.stringify(registry, null, 1));
// same data as a script so showcase.html works when opened straight from disk (file:// blocks fetch)
writeFileSync(join(root, "registry.js"), `/* AUTO-GENERATED by node ds/build-figma.mjs */\nwindow.RallyzRegistry = ${JSON.stringify(registry)};\n`);

console.log(`icons: ${Object.keys(icons).length} (mono ${Object.values(icons).filter((i) => i.mono).length})`);
console.log(`paint vars: ${paintVars.length}, text styles: ${styles.textStyles.length}, components: ${registry.components.length}`);
