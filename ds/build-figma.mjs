#!/usr/bin/env node
/**
 * Rallyz DS — build code assets from the Figma export in ds/figma/.
 *
 *   ds/figma/styles.json       get_style_details (text + paint styles)
 *   ds/figma/variables.json    get_local_variables (Foundation collection)
 *   ds/figma/components.json   get_local_components scope=all
 *   ds/figma/spec/*.json       get_node_spec per component (lossless tree)
 *   ds/figma/icon-svg/*.svg    export_node_svg per Icon-page component
 *   ds/figma/glyph-svg/*.svg   export_node_svg for vectors that live inside components
 *
 * Outputs: ds/icons/**.svg, ds/icons.js, ds/tokens.css, ds/registry.json
 * Usage:   node ds/build-figma.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = dirname(fileURLToPath(import.meta.url));
const fig = join(root, "figma");
const read = (p) => JSON.parse(readFileSync(join(fig, p), "utf8"));

const styles = read("styles.json");
const components = read("components.json");

/* ------------------------------------------------------------------ */
/* Icons                                                               */
/* ------------------------------------------------------------------ */

function iconKey(name) {
  // eslint-disable-next-line no-control-regex
  let k = name.replace(/[\u0000-\u001f]/g, "").trim().replace(/\s*\/\s*/g, "/");
  k = k.replace(/^icon\//i, "");
  return k.replace(/\s+/g, "_");
}

const COLOR_RE = /(fill|stroke)="(#[0-9A-Fa-f]{6})"/g;

function processSvg(svg, prefix) {
  svg = svg.replace(/(fill|stroke)="(white|black)"/gi, (_, a, c) => `${a}="${c.toLowerCase() === "white" ? "#FFFFFF" : "#000000"}"`);
  // colours inside <mask>/<clipPath> are luminance helpers, not paint
  const paintOnly = svg.replace(/<(mask|clipPath)\b[\s\S]*?<\/\1>/g, "");
  const colors = new Set([...paintOnly.matchAll(COLOR_RE)].map((m) => m[2].toUpperCase()));
  const rich = /<(image|pattern|linearGradient|radialGradient|filter)\b/.test(svg);
  const mono = colors.size <= 1 && !rich;
  let out = svg.replace(/\r?\n/g, "").replace(/>\s+</g, "><").trim();
  // unique ids so many inline icons can share one page
  out = out
    .replace(/\bid="([^"]+)"/g, (_, id) => `id="${prefix}-${id}"`)
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${prefix}-${id})`)
    .replace(/(xlink:href|href)="#([^"]+)"/g, (_, a, id) => `${a}="#${prefix}-${id}"`);
  const defaultColor = colors.size ? [...colors][0] : null;
  if (mono && defaultColor) {
    const masks = [];
    out = out.replace(/<(mask|clipPath)\b[\s\S]*?<\/\1>/g, (m) => `\u0000${masks.push(m) - 1}\u0000`);
    out = out.replace(COLOR_RE, (m, attr, hex) => (hex.toUpperCase() === defaultColor ? `${attr}="currentColor"` : m));
    // eslint-disable-next-line no-control-regex
    out = out.replace(/\u0000(\d+)\u0000/g, (_, i) => masks[Number(i)]);
  }
  const w = Number(/width="([\d.]+)"/.exec(out)?.[1] || 24);
  const h = Number(/height="([\d.]+)"/.exec(out)?.[1] || 24);
  return { svg: out, mono, color: defaultColor, w, h, colors: [...colors] };
}

const iconsOut = join(root, "icons");
if (existsSync(iconsOut)) rmSync(iconsOut, { recursive: true });
const icons = {};

for (const c of components.components.filter((x) => x.page === "Icon")) {
  const file = join(fig, "icon-svg", c.id.replace(":", "_") + ".svg");
  if (!existsSync(file)) continue;
  let key = iconKey(c.name);
  if (icons[key]) key = `${key}~${c.id.replace(":", "_")}`;
  const p = processSvg(readFileSync(file, "utf8"), "rzi" + c.id.replace(/[^0-9]/g, ""));
  icons[key] = { ...p, figmaId: c.id, figmaName: c.name };
}
for (const f of readdirSync(join(fig, "glyph-svg"))) {
  const key = "glyph/" + f.replace(/\.svg$/, "");
  const p = processSvg(readFileSync(join(fig, "glyph-svg", f), "utf8"), "rzg" + key.replace(/[^a-z0-9]/gi, ""));
  // multi-path glyphs that are visually one colour still benefit from currentColor
  icons[key] = { ...p, figmaId: null, figmaName: key };
}

for (const [key, v] of Object.entries(icons)) {
  const path = join(iconsOut, key.replace(/~/g, "--") + ".svg");
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, v.svg + "\n");
}

const iconMeta = Object.fromEntries(
  Object.entries(icons).map(([k, v]) => [k, { w: v.w, h: v.h, mono: v.mono, color: v.color, figmaId: v.figmaId, figmaName: v.figmaName }]),
);
const iconSvgs = Object.fromEntries(Object.entries(icons).map(([k, v]) => [k, v.svg]));

writeFileSync(
  join(root, "icons.js"),
  `/* AUTO-GENERATED by node ds/build-figma.mjs — SVG exported from Figma (Icon page + component glyphs). */
/* Mono icons use currentColor (default colour in meta.color); multi-colour illustrations keep Figma fills. */
export const iconSvgs = ${JSON.stringify(iconSvgs, null, 0)};

export const iconMeta = ${JSON.stringify(iconMeta, null, 0)};

/**
 * Inline SVG icon.
 * @param {string} name  key, e.g. "line/ic24_add", "solid/profile", "flat/ic40_message", "glyph/chevron-down"
 * @param {{size?: number, width?: number, height?: number, color?: string, label?: string, className?: string}} [opts]
 * @returns {HTMLSpanElement}
 */
export function Icon(name, opts = {}) {
  const svg = iconSvgs[name];
  const meta = iconMeta[name];
  const span = document.createElement("span");
  span.className = "rz-icon" + (opts.className ? " " + opts.className : "");
  span.dataset.icon = name;
  if (!svg) {
    console.warn("[rallyz] unknown icon:", name);
    return span;
  }
  span.innerHTML = svg;
  const w = opts.width ?? opts.size ?? meta.w;
  const h = opts.height ?? opts.size ?? meta.h;
  span.style.width = w + "px";
  span.style.height = h + "px";
  if (meta.mono) span.style.color = opts.color ?? meta.color ?? "currentColor";
  if (opts.label) {
    span.setAttribute("role", "img");
    span.setAttribute("aria-label", opts.label);
  } else {
    span.setAttribute("aria-hidden", "true");
  }
  return span;
}

export function iconNames() {
  return Object.keys(iconSvgs);
}
`,
);

/* ------------------------------------------------------------------ */
/* Tokens                                                              */
/* ------------------------------------------------------------------ */

const slug = (s) =>
  s
    .replace(/Primary_Fresh green/, "primary")
    .replace(/Secondary_Blue/, "secondary")
    .replace(/^Green\/GGreen$/, "green-g")
    .replace(/^Blue\/GBlue$/, "blue-g")
    .replace(/^(Green|Blue|Gray)\//, "")
    .replace(/_/g, "-")
    .replace(/\s+/g, "-")
    .toLowerCase();

const paintVars = [];
const paintByName = {};
for (const p of styles.paintStyles) {
  if (!p.hex) continue;
  let name;
  if (p.name === "Black") name = "black";
  else if (p.name === "White") name = "white";
  else if (p.name === "Red") name = "red";
  else if (p.name === "Slide/Dark fill") name = "device";
  else if (/primary|secondary/i.test(slug(p.name))) name = slug(p.name);
  else {
    const fam = p.name.split("/")[0].toLowerCase();
    const s = slug(p.name);
    name = s.startsWith(fam) ? s : `${fam}-${s}`;
  }
  paintByName[p.name] = name;
  paintVars.push(`  --rz-${name}: ${p.hex}; /* ${p.name} */`);
}

const weight = { Regular: 400, Medium: 500, Bold: 700, Light: 300 };
const typeVars = [];
const typeClasses = [];
for (const t of styles.textStyles) {
  const k = t.name.toLowerCase().replace("/", "-");
  const w = weight[t.fontName.style] ?? 400;
  const lh = t.lineHeight.unit === "PIXELS" ? `${t.lineHeight.value}px` : "normal";
  typeVars.push(`  --rz-type-${k}: ${w} ${t.fontSize}px/${lh} var(--rz-font-sans); /* ${t.name} */`);
  // legacy split vars (kept for existing pages)
  typeVars.push(`  --rz-type-${k}-size: ${t.fontSize}px; --rz-type-${k}-line: ${lh}; --rz-type-${k}-weight: ${w};`);
  typeClasses.push(`.rz-t-${k}, .rz-type-${k} { font: var(--rz-type-${k}); letter-spacing: 0; }`);
}

