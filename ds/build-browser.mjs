#!/usr/bin/env node
/**
 * Bundle icons.js + components.js into one IIFE (window.Rallyz) that works on file:// and http://.
 * Usage: node ds/build-browser.mjs   (run after node ds/build-figma.mjs)
 */
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = dirname(fileURLToPath(import.meta.url));
const strip = (src) =>
  src
    .replace(/^import [^\n]*\n/gm, "")
    .replace(/^export \{[^}]*\};?\n/gm, "")
    .replace(/^export (const|function|let) /gm, "$1 ");

const icons = strip(readFileSync(join(root, "icons.js"), "utf8"));
const components = strip(readFileSync(join(root, "components.js"), "utf8"));

const out = `/* AUTO-GENERATED by node ds/build-browser.mjs — do not edit. */
(function (global) {
"use strict";
${icons}
${components}
Rallyz.iconNames = iconNames;
Rallyz.iconMeta = iconMeta;
global.Rallyz = Rallyz;
})(typeof window !== "undefined" ? window : globalThis);
`;
writeFileSync(join(root, "rallyz.browser.js"), out);
console.log("wrote ds/rallyz.browser.js", (out.length / 1024).toFixed(0) + " KB");
